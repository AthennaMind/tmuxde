// Regenerates apps/site/src/lib/demo/qr-glyph.ts from a real QR encoding.
// Uses the same encoder and the same small-mode renderer the CLI's banner uses.
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";

const require = createRequire("/home/ubuntu/tmux-remote-ai/package.json");
const base =
  "./node_modules/.pnpm/qrcode-terminal@0.12.0/node_modules/qrcode-terminal";
const QRCode = require(`${base}/vendor/QRCode`);
const Level = require(`${base}/vendor/QRCode/QRErrorCorrectLevel`);
const qrcode = require(`${base}/lib/main.js`);

const PAYLOAD = "https://app.mtmux.com/j#492716384";

const qr = new QRCode(-1, Level.L);
qr.addData(PAYLOAD);
qr.make();
const n = qr.getModuleCount();
const matrix = [];
for (let r = 0; r < n; r++) {
  let row = "";
  for (let c = 0; c < n; c++) row += qr.isDark(r, c) ? "1" : "0";
  matrix.push(row);
}

let small = "";
qrcode.generate(PAYLOAD, { small: true }, (out) => {
  small = out;
});
const rows = small.split("\n").filter((line) => line.length > 0);
const width = new Set(rows.map((r) => [...r].length));
if (width.size !== 1) throw new Error("ragged rows");

const file = `/**
 * The QR the home page shows — a real one.
 *
 * Both forms below encode ${"`"}QR_PAYLOAD${"`"}: the join URL the CLI puts in its
 * banner, ${"`"}<app origin>/j#<code>${"`"} (see ${"`"}joinUrl()${"`"} in
 * ${"`"}apps/cli/src/commands/start.ts${"`"}). It is a real, scannable code, generated by
 * the same encoder at the same error-correction level the CLI uses — the demo
 * code it carries is long expired, so scanning it lands on the pairing page
 * and says so, which is the honest outcome and not a broken picture.
 *
 * This file is generated. To change the payload, edit ${"`"}PAYLOAD${"`"} in
 * ${"`"}scripts/generate-qr.mjs${"`"} and run ${"`"}node scripts/generate-qr.mjs${"`"}.
 *
 * - ${"`"}QR_MATRIX${"`"} is the module grid, one string per row, "1" = dark module.
 *   ${"`"}<QrCode>${"`"} draws it as an SVG, which is what the hero uses.
 * - ${"`"}QR_ROWS${"`"} is the half-block rendering ${"`"}qrcode-terminal${"`"} emits in small
 *   mode — literally what lands in your scrollback — used by the demo cast so
 *   the replayed terminal shows the same bytes a real one would.
 *
 * Each row is the same length by construction, checked by ${"`"}player.test.ts${"`"},
 * because a ragged row would visibly shear the block.
 */

/** What the code encodes. The join URL the CLI prints, with the demo code. */
export const QR_PAYLOAD = ${JSON.stringify(PAYLOAD)};

/** ${n}×${n} modules. "1" is a dark module, "0" a light one. */
export const QR_MATRIX: readonly string[] = [
${matrix.map((r) => `  ${JSON.stringify(r)},`).join("\n")}
];

/** ${rows.length} rows of half-blocks — one glyph per two QR modules vertically. */
export const QR_ROWS: readonly string[] = [
${rows.map((r) => `  ${JSON.stringify(r)},`).join("\n")}
];

export const QR_WIDTH = QR_ROWS[0]?.length ?? 0;
`;

writeFileSync(
  "/home/ubuntu/tmux-remote-ai/apps/site/src/lib/demo/qr-glyph.ts",
  file,
);
console.log(`wrote ${n}x${n} matrix, ${rows.length} half-block rows`);
